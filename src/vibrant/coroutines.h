inline void original::coroutine::task<void>::sync(syncPoint& spt) const
{
    if (this->empty())
        throw sysError("Can not sync with an empty task");
    if (this->started())
        throw sysError("Can not sync with a started task");
    this->handle_.promise().spt_ = &spt;
}

inline bool original::coroutine::task<void>::start() const noexcept {
    if (this->empty())
        return false;

    switch (auto& promise = this->handle_.promise(); promise.state_) {
        case state::STANDBY:
            if (this->hasExecutor()){
                promise.state_ = state::RUNNING;
                promise.executor_->schedule(this->handle_);
                return true;
            }
            break;
        case state::RUNNING:
        case state::FINISHED:
        default:
            break;
    }
    return false;
}

inline bool original::coroutine::task<void>::hasExecutor() const noexcept
{
    if (this->empty())
        return false;

    return this->handle_.promise().executor_;
}

inline original::coroutine::task<void>&
original::coroutine::task<void>::via(executor& executor) noexcept {
    if (this->empty())
        return *this;

    auto& promise = this->handle_.promise();
    promise.executor_ = &executor;
    return *this;
}

