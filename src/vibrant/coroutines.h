template <typename TYPE>
original::coroutine::generator<TYPE>
original::coroutine::generator<TYPE>::promise_type::get_return_object()
{
    return generator{handle::from_promise(*this)};
}

template <typename TYPE>
std::suspend_always original::coroutine::generator<TYPE>::promise_type::initial_suspend()
{
    return std::suspend_always{};
}

template <typename TYPE>
std::suspend_always original::coroutine::generator<TYPE>::promise_type::final_suspend() noexcept
{
    return std::suspend_always{};
}

template <typename TYPE>
void original::coroutine::generator<TYPE>::promise_type::return_void() {}

template <typename TYPE>
std::suspend_always original::coroutine::generator<TYPE>::promise_type::yield_value(TYPE value)
{
    if (!this->initial_status) {
        this->initial_status = true;
    }
    this->value_ = std::move(value);
    return std::suspend_always{};
}

template <typename TYPE>
void original::coroutine::generator<TYPE>::promise_type::unhandled_exception()
{
    this->e_ = std::current_exception();
}

template <typename TYPE>
void original::coroutine::generator<TYPE>::promise_type::rethrow_if_exception() const
{
    if (this->e_)
        std::rethrow_exception(this->e_);
}

template <typename TYPE>
original::coroutine::generator<TYPE>::iterator::iterator() : gen_(nullptr), end_(true) {}

template <typename TYPE>
original::coroutine::generator<TYPE>::iterator::iterator(generator* gen) : gen_(gen), end_(false)
{
    if (!this->gen_) {
        this->end_ = true;
        return;
    }
    ++*this;
}

template <typename TYPE>
original::coroutine::generator<TYPE>::iterator&
original::coroutine::generator<TYPE>::iterator::operator++()
{
    if (this->end_)
        return *this;
    if (auto gen_next = this->gen_->next(); !gen_next) {
        this->end_ = true;
    }
    return *this;
}

template <typename TYPE>
TYPE original::coroutine::generator<TYPE>::iterator::operator*()
{
    if (this->end_)
        throw nullPointerError("Dereferencing end iterator");
    return *this->gen_->peek();
}

template <typename TYPE>
bool original::coroutine::generator<TYPE>::iterator::operator!=(const iterator& other) const
{
    return !(*this == other);
}

template <typename TYPE>
bool original::coroutine::generator<TYPE>::iterator::operator==(const iterator& other) const
{
    if (this->end_ && other.end_)
        return true;
    if (this->end_ != other.end_)
        return false;
    return this->gen_ == other.gen_;
}

template <typename TYPE>
original::coroutine::generator<TYPE>::generator(generator&& other) noexcept
{
    this->handle_ = other.handle_;
    other.handle_ = nullptr;
}

template <typename TYPE>
original::coroutine::generator<TYPE>&
original::coroutine::generator<TYPE>::operator=(generator&& other) noexcept
{
    if (this == &other) {
        return *this;
    }

    if (this->handle_) {
        this->handle_.destroy();
    }

    this->handle_ = other.handle_;
    other.handle_ = nullptr;
    return *this;
}

template <typename TYPE>
original::coroutine::generator<TYPE>::generator(handle h) : handle_(std::move(h)) {}

template <typename TYPE>
original::coroutine::generator<TYPE>::iterator
original::coroutine::generator<TYPE>::begin()
{
    return iterator{this};
}

template <typename TYPE>
original::coroutine::generator<TYPE>::iterator
original::coroutine::generator<TYPE>::end()
{
    return iterator{};
}

template <typename TYPE>
bool original::coroutine::generator<TYPE>::launched() const
{
    return this->handle_.promise().initial_status;
}

template <typename TYPE>
bool original::coroutine::generator<TYPE>::hasNext() const
{
    return this->handle_ && !this->handle_.done();
}

template <typename TYPE>
original::alternative<TYPE> original::coroutine::generator<TYPE>::peek() const
{
    return this->handle_.promise().value_;
}

template <typename TYPE>
original::alternative<TYPE>
original::coroutine::generator<TYPE>::next()
{
    if (!this->hasNext())
        return alternative<TYPE>{};

    this->handle_.resume();
    this->handle_.promise().rethrow_if_exception();

    if (!this->hasNext())
        return alternative<TYPE>{};

    return this->handle_.promise().value_;
}

template <typename TYPE>
original::coroutine::generator<TYPE>::~generator()
{
    if (this->handle_)
        this->handle_.destroy();
}

template <typename Pred, typename Then, typename Else>
original::coroutine::taskCondition<Pred, Then, Else>::taskCondition(Pred p, Then t, Else e)
    : pred_(std::move(p)), then_(std::move(t)), else_(std::move(e)) {}

template <typename ... Args>
template <typename TYPE, bool Prev>
original::coroutine::taskArgs<Args...>::bridge<TYPE, Prev>::bridge(taskArgs args, task<TYPE> task)
    : taskArgs_(std::move(args)), task_(std::move(task)) {}

template <typename ... Args>
template <typename TYPE, bool Prev>
template <typename ... Others>
original::coroutine::taskArgs<Others...>::template bridge<TYPE, Prev>
original::coroutine::taskArgs<Args...>::bridge<TYPE, Prev>::operator|(taskArgs<Others...>&& args)
{
    auto new_args = std::move(this->taskArgs_) |  std::move(args);
    using bridgeType = taskArgs<Others...>::template bridge<TYPE, Prev>;
    return bridgeType{std::move(new_args), std::move(this->task_)};
}

template <typename ... Args>
template <typename TYPE, bool Prev>
template <typename ... Others>
original::coroutine::taskArgs<Args..., Others...>::template bridge<TYPE, Prev>
original::coroutine::taskArgs<Args...>::bridge<TYPE, Prev>::operator>>(taskArgs<Others...>&& args)
{
    auto new_args = std::move(this->taskArgs_) >> std::move(args);
    using bridgeType = taskArgs<Args..., Others...>::template bridge<TYPE, Prev>;
    return bridgeType(std::move(new_args), std::move(this->task_));
}

template <typename ... Args>
template <typename TYPE, bool Prev>
template <typename Callback>
auto original::coroutine::taskArgs<Args...>::bridge<TYPE, Prev>::operator|(Callback&& c)
{
    if (this->task_.empty())
        throw valueError("Can not combine empty tasks");

    auto exec = this->taskArgs_.executor_;
    if (!exec)
        throw sysError("Tasks without a specified executor cannot be combined");
    this->task_.via(*exec);

    auto bridge = []<typename Func>(executor* exe, task<TYPE> t, Func f) mutable -> task<std::invoke_result_t<Func>> {
        auto new_task = std::move(t) | std::forward<Func>(f);
        new_task.via(*exe);
        co_return co_await new_task;
    };

    using Func = std::decay_t<Callback>;
    Func func_copy{std::forward<Callback>(c)};
    auto task = bridge(exec, std::move(this->task_), std::move(func_copy));
    task.via(*exec);
    return task;
}

template <typename ... Args>
template <typename TYPE, bool Prev>
template <typename Callback>
auto original::coroutine::taskArgs<Args...>::bridge<TYPE, Prev>::operator>>(Callback&& c)
{
    if (this->task_.empty())
        throw valueError("Can not combine empty tasks");

    auto exec = this->taskArgs_.executor_;
    if (!exec)
        throw sysError("Tasks without a specified executor cannot be combined");
    this->task_.via(*exec);

    using Func = std::decay_t<Callback>;
    Func func_copy{std::forward<Callback>(c)};
    if constexpr (!Prev) {
        auto bridge = []<typename Func, typename... Params>(executor* exe, task<TYPE> t, Func f, taskArgs<Params...> args)
            -> task<std::invoke_result_t<Func, Params...>> {
            co_await t;
            co_return co_await makeTask(*exe, std::move(f), std::move(args.unbind()));
        };
        auto task = bridge(exec, std::move(this->task_), std::move(func_copy), std::move(this->taskArgs_));
        task.via(*exec);
        return task;
    } else {
        auto bridge = []<typename Func, typename... Params>(executor* exe, task<TYPE> t, Func f, taskArgs<Params...> args)
            -> task<std::invoke_result_t<Func, TYPE, Params...>> {
            TYPE tmp = co_await t;
            auto new_args = tuple{std::move(tmp)} + std::move(args.unbind());
            co_return co_await makeTask(*exe, std::move(f), std::move(new_args));
        };
        auto task = bridge(exec, std::move(this->task_), std::move(func_copy), std::move(this->taskArgs_));
        task.via(*exec);
        return task;
    }
}

