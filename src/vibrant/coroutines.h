template <typename TYPE>
original::coroutine::task<TYPE>::awaitable::awaitable(handle h) : handle_(h) {}

template <typename TYPE>
bool original::coroutine::task<TYPE>::awaitable::await_ready() const noexcept
{
    return !this->handle_ || this->handle_.done();
}

template <typename TYPE>
void original::coroutine::task<TYPE>::awaitable::await_suspend(std::coroutine_handle<> waiter) noexcept
{
    auto& promise = this->handle_.promise();
    promise.continuation_ = waiter;

    switch (promise.state_) {
        case state::STANDBY:
        default:
            promise.state_ = state::RUNNING;
        case state::RUNNING:
            if (promise.executor_)
                promise.executor_->schedule(this->handle_);
            break;
        case state::FINISHED:
            break;
    }
}

template <typename TYPE>
TYPE original::coroutine::task<TYPE>::awaitable::await_resume() const
{
    auto& promise = this->handle_.promise();
    promise.rethrow_if_exception();
    return std::move(*promise.value_);
}

template<typename TYPE>
bool original::coroutine::task<TYPE>::finalAwaitable::await_ready() noexcept // NOLINT
{
    return false;
}

template<typename TYPE>
void original::coroutine::task<TYPE>::finalAwaitable::await_suspend(
     std::coroutine_handle<promise_type> handle) noexcept
{
    auto& promise = handle.promise();
    promise.state_ = state::FINISHED;

    if (promise.continuation_ && promise.executor_) {
        promise.executor_->schedule(promise.continuation_);
    }

    if (const auto spt = promise.spt_) {
        spt->arrive();
    }
}

