{
    return !this->handle_ || this->handle_.done();
}

inline void original::coroutine::task<void>::awaitable::await_suspend(const std::coroutine_handle<> waiter) noexcept // NOLINT
{
    auto& promise = this->handle_.promise();
    promise.continuation_ = waiter;

    switch (promise.state_) {
    case state::STANDBY:
    default:
        promise.state_ = state::RUNNING;
    case state::RUNNING:
        if (promise.executor_)
            promise.executor_->schedule(this->handle_);
        break;
    case state::FINISHED:
        break;
    }
}

inline void original::coroutine::task<void>::awaitable::await_resume() const
{
    const auto& promise = this->handle_.promise();
    promise.rethrow_if_exception();
}

inline bool original::coroutine::task<void>::finalAwaitable::await_ready() noexcept // NOLINT
{
    return false;
}

inline void original::coroutine::task<void>::finalAwaitable::await_suspend( // NOLINT
     const std::coroutine_handle<promise_type> handle) noexcept
{
    auto& promise = handle.promise();
    promise.state_ = state::FINISHED;

    if (promise.continuation_ && promise.executor_) {
        promise.executor_->schedule(promise.continuation_);
    }

    if (const auto spt = promise.spt_) {
        spt->arrive();
    }
}

inline void original::coroutine::task<void>::finalAwaitable::await_resume() noexcept {} // NOLINT

