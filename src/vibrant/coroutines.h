template <typename Callback, typename ... Args>
auto original::coroutine::makeTask(Callback&& c, Args&&... args)
    -> task<std::invoke_result_t<Callback, Args...>>
{
    using Return = std::invoke_result_t<Callback, Args...>;
    using Func  = std::decay_t<Callback>;
    using Tuple = std::tuple<std::decay_t<Args>...>;

    Func func_copy{std::forward<Callback>(c)};
    Tuple args_copy{std::forward<Args>(args)...};
    auto run_impl = [](Func f, Tuple tup) -> task<Return>
    {
        co_return std::apply(std::move(f), std::move(tup));
    };
    auto t = run_impl(std::move(func_copy), std::move(args_copy));
    return t;
}

template<typename Callback, typename... Args>
auto original::coroutine::makeTask(executor& executor, Callback&& c, Args&&... args)
     -> task<std::invoke_result_t<Callback, Args...>> {
    using Return = std::invoke_result_t<Callback, Args...>;
    task<Return> t = makeTask(std::forward<Callback>(c), std::forward<Args>(args)...);
    t.via(executor);
    return t;
}

template <typename Callback, typename ... Args>
auto original::coroutine::makeTask(Callback&& c, tuple<Args...> args)
    -> task<std::invoke_result_t<Callback, Args...>>
{
    return apply(
               [&](auto&&... unpacked) {
                   return makeTask(std::forward<Callback>(c), std::move(unpacked)...);
               },
               std::move(args)
           );
}

template <typename Callback, typename ... Args>
auto original::coroutine::makeTask(executor& executor, Callback&& c, tuple<Args...> args)
    -> task<std::invoke_result_t<Callback, Args...>>
{
    using Return = std::invoke_result_t<Callback, Args...>;
    task<Return> t = makeTask(std::forward<Callback>(c), std::move(args));
    t.via(executor);
    return t;
}

template <typename TYPE>
TYPE original::coroutine::spinRun(task<TYPE> t)
{
    if (t.empty())
        throw valueError("Can not run an empty task");
    if (t.finished())
        return t.result();
    if (t.started())
        throw valueError("Can not run a task while started");
    if (!t.hasExecutor())
        throw valueError("Can not run a task without a specified executor");

    t.start();
    u_integer spin = 0;
    while (!t.finished()) {
        if (spin < 50) {
            thread::yield();
        } else if (spin < 200) {
            thread::sleep(microseconds(50));
        } else {
            thread::sleep(milliseconds(1));
        }
        spin += 1;
    }
    return t.result();
}

template <typename TYPE>
TYPE original::coroutine::run(task<TYPE> t)
{
    if (t.empty())
        throw valueError("Can not run an empty task");
    if (t.finished())
        return t.result();
    if (t.started())
        throw valueError("Can not run a task while started");
    if (!t.hasExecutor())
        throw valueError("Can not run a task without a specified executor");

    syncPoint pt{2};
    t.sync(pt);
    if (const bool started = t.start(); !started) {
        throw sysError("Can not run a task");
    }
    pt.arrive();
    return t.result();
}

inline bool original::coroutine::run(const task<void>& t)
{
    if (t.empty())
        throw valueError("Can not run an empty task");
    if (t.finished())
        return true;
    if (t.started())
        throw valueError("Can not run a task while started");
    if (!t.hasExecutor())
        throw valueError("Can not run a task without a specified executor");

    syncPoint pt{2};
    t.sync(pt);
    if (const bool started = t.start(); !started) {
        return false;
    }
    pt.arrive();
    return true;
}

template <typename ... Args>
original::tuple<original::someType<std::is_void_v<Args>, bool, Args>...>
original::coroutine::whenAll(task<Args>... ts)
{
    if ((ts.empty() || ...)) {
        throw valueError("Can not use whenAll with empty tasks");
    }

    if (const bool all_have_executor = (ts.hasExecutor() && ...); !all_have_executor) {
        throw sysError("All tasks must have a specified executor for whenAll");
    }

    if ((ts.started() || ...)) {
        throw valueError("Can not use whenAll with already started tasks");
    }

    syncPoint pt{sizeof...(ts) + 1};
    (ts.sync(pt), ...);
    if (const bool all_started = (ts.start() && ...); !all_started) {
        throw sysError("Failed to start one or more tasks");
    }
    pt.arrive();

    return original::tuple<someType<std::is_void_v<Args>, bool, Args>...> {
        []<typename T>(task<T>& t) -> someType<std::is_void_v<T>, bool, T> {
            if constexpr (std::is_void_v<T>) {
                t.result();
                return true;
            } else {
                return t.result();
            }
        }(ts)...
    };
}

